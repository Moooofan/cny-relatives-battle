// Rebuilds src/content/questions/index.ts from every question file on disk.
// Writers add files under src/content/questions/<bossId|generic>/<topic>.ts
// (each `export default [...] satisfies Question[]`) and run `pnpm content:index`.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..", "src", "content", "questions");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith(".ts") && name !== "index.ts" && !name.endsWith(".test.ts")) out.push(p);
  }
  return out;
}

const files = walk(root).map((p) => relative(root, p).split(sep).join("/").replace(/\.ts$/, ""));
const imports = files.map((f, i) => `import q${i} from "./${f}";`).join("\n");
const spread = files.map((_, i) => `  ...q${i},`).join("\n");

const body = `// AUTO-GENERATED by scripts/build-content-index.mjs — do not edit by hand.
// Run \`pnpm content:index\` after adding or removing question files.
import type { Question } from "@/content/types";
${imports}

export const QUESTIONS: Question[] = [
${spread}
];

export const QUESTION_FILES = ${JSON.stringify(files, null, 2)} as const;
`;

writeFileSync(join(root, "index.ts"), body);
console.log(`content index: ${files.length} question files`);
